-- 024 · 对话是**一等实体** —— 一个项目下面可以有多条对话
--
-- ── 它补的是什么 ──────────────────────────────────────────────────
--
-- 用户原话(2026-10-06):
--
--   「一个对话只能对应一个项目吗 …… 我们需要支撑多对话对应一个项目的某个版本」
--
-- 而 2026-10-06 之前,`web/src/stores/chat.ts` 的文件头写着:
--
--   「项目」是一等实体,每个项目**一条连续对话** → 本项目 = `projectId`;
--
-- 对话页是个**单指针**(`projectId: string | null`),没有会话列表。
--
-- ── 关键发现:**存储层其实早就支持了** ────────────────────────────
--
-- `project_sessions` 上**只有一条**唯一索引 —— `idx_session_single_intake`,
-- 而它只约束 `project_id IS NULL` 的那一条接待会话。一个项目下面挂**任意多条**
-- 会话在 schema 层面**一直合法**。
--
-- 真正把模型钉死在 1:1 的是**上面那四层**:
--   ① WS `send` 命令**只带 `projectId`**,没有 `sessionId` —— 前端**无法指定**
--      发到哪条会话;
--   ② `ensureSession()` 按 `(project_id, channel)` 找**最新一条**复用 —— 发哪条
--      不由调用者决定;
--   ③ 会话池的键是 `(上下文, agent)` 而「上下文」= `projectId` —— 同一个项目的
--      两条对话会**共用同一个 SDK 会话**,模型分不清;
--   ④ 前端没有会话列表,看不见也切不了。
--
-- ⇒ 024 只动第 ① 层的**前置**:给会话一个**身份**(是哪条线)与一个**可读的标题**。
-- 后面三层由 024 之后的接线一次做完(见 commit `feat(web): 对话页多会话`)。
--
-- ── 为什么 `kind` 只有两个取值 ─────────────────────────────────────
--
--   · `main`   —— 项目的**主对话**。它就是 `ensureSession` 按 channel 复用的那一条,
--                 也是**排空器触发的回合**落的地方(待办不是「某条对话」,它是项目级的)。
--   · `thread` —— 甲方**主动另开**的一条对话线(「W1–W7 调研推进」「收口与验收」
--                 「v2 的想法」这类)。它的价值是**上下文不互相污染**:同一项目的
--                 若干条线各自有自己的 SDK 会话,不会越滚越大。
--
-- ⚠️ **不做「按需自动开线」**:什么时候该另开一条线、叫什么名字,**平台从库里
-- 推不出来**(§2.11.3:规则不做语义猜测)。所以由甲方显式开、业务经理给标题。
--
-- ── 存量行的处置(如实写)──────────────────────────────────────────
--
-- 可空 + `DEFAULT 'main'` ⇒ 024 之前的每一行都是 `main`,而那是**事实**:
-- 它们确实是「每个项目的那一条对话」。**不是**猜出来的。
-- ⚠️ `title` 保持 `NULL` 而不是回填一个「对话 1」 —— 名字是给甲方看的,
-- 编一个出来会让人以为甲方真的这么命名过。
--
-- ── 本迁移只做加法 ──────────────────────────────────────────────
--
-- 一条 `ALTER TABLE ... ADD COLUMN`(另一条是**可空、无约束**的 title)。
-- **一行 DROP 都没有**,不改任何已有列、不重建表。
-- ⚠️ 与 016/020 文件头记的那个「第 N 张引用子表」的清单**无关**:
-- `project_sessions` 没有子表(没有别的表 REFERENCES 它),所以将来若重建它,
-- 需要一并处置的只有 `session_messages.session_id`(010 建的那条 FK)。
-- ⇒ 024 **不是** `INTENTIONAL_REBUILDS` 的成员。

-- ── ① 这条会话是哪条线 ────────────────────────────────────────────
--
-- `main` = 主对话(排空器触发的回合落这里);`thread` = 甲方另开的对话线。
-- 有 CHECK —— 这是一个**稳定的**两值闭集,与 022 的 `todo_kind` 不同
-- (那一列的取值域随 `TODO_KINDS` 变,所以故意不建 CHECK,见那份迁移的文件头)。
ALTER TABLE project_sessions ADD COLUMN kind TEXT NOT NULL DEFAULT 'main'
  CHECK (kind IN ('main', 'thread'));

-- ── ② 这条线叫什么 ────────────────────────────────────────────────
--
-- **可空且不编**:甲方开线时自己起名、或让业务经理起;没起就是 `NULL`。
-- 读面把 `NULL` 显示成「对话」(而不是「未命名」—— 后者听起来像故障)。
ALTER TABLE project_sessions ADD COLUMN title TEXT;