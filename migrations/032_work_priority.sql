-- 032 · 工作项显式优先级(要事第一的工程化)
--
-- ── 它补的是什么 ────────────────────────────────────────────────
--
-- 此前工作项之间只有 `created_at` 先后(排空器里实际是 `execute_work:<id>` 的
-- key 字典序),「哪条先跑」全看创建顺序与 id 拼法。priority 是一个显式档位:
--   0 = 最紧急 … 9 = 最低,缺省 3。
-- 排序判据的落点在 `runtime/dispatcher.ts` 的 `collectTodos`(排空器唯一的
-- 「下一步该谁跑」判定):同一种待办内,**数字小的先派**;同优先级内保持
-- 原有次序(key 字典序)。
--
-- ── 为什么是纯加列,不是重建表 ────────────────────────────────────
--
-- 与 030(`knowledge_tier`)/ 031(`acceptance_criteria`)同一条先例:
-- 纯加列、NOT NULL 带默认、无 CHECK —— 取值域(0–9 的整数档位)在读写
-- 两侧的 TypeScript 里校验(`repo/works.ts` 的 `clampWorkPriority` /
-- `rowToWork`),不靠 schema 闭集。给 priority 建 CHECK 的唯一后果是:
-- 将来想改档位边界(比如加到 0–15)就要写一条重建 `works` 表的迁移 ——
-- `works` 被三张子表引用(`work_deps` 两条边 + `artifacts.work_id`),
-- 重建成本与「多防一个越界值」完全不成比例。
--
-- ── 存量行 = 缺省 3 ─────────────────────────────────────────────
--
-- 存量工作项创建时平台还没有「优先级」这个概念,给它们回填任何一个档位
-- 都是**编造一个平台没做过的判断**(030 对 tier 不回填、031 对判据不回填,
-- 同一条纪律)。DEFAULT 3 是「中等」而不是「某次判断的结果」—— 它表达
-- 的恰恰是「没有判断过」。新写入的显式优先级由 `work_create` / `work_update`
-- 带进来,clamp 到 0–9。
--
-- ── 本迁移只做加法 ──────────────────────────────────────────────
--
-- 一条 `ALTER TABLE ... ADD COLUMN`,不改任何已有列、不重建表、不动任何
-- 既有约束与索引。`works` **不是**任何「同一张表被两个迁移创建」意义的
-- 重建(007 创建、013/032 都是 ALTER),`tests/platform/migrations.test.ts`
-- 的重名守卫不受影响;它的「ALTER 目标必须先存在」判据由 007 满足。

ALTER TABLE works ADD COLUMN priority INTEGER NOT NULL DEFAULT 3;
