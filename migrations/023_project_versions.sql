-- 023 · 项目的**版本链** —— 「下一个版本」是新项目,但它记得自己是第几版
--
-- ── 它补的是什么 ──────────────────────────────────────────────────
--
-- 真机现场(2026-10-06,用户原话):
--
--   「项目交付之后,是否需要重新打开,或者有新的版本,我觉得可以在原对话中继续
--     对话的,如果有必要,可以新开一个版本,否则就是纯和业务经理交流」
--
-- 而修完 P2(收口规则)之后暴露出紧接着的第二个洞:项目一旦 `done`,**新版本无处可去**
-- —— `project_open` 只能开一个「全新的、毫无来历的项目」。于是「同一个交付物的
-- 第二次演进」和「用户临时起意的另一件事」在库里长得一模一样,甲方与业务经理
-- 都分不出来。
--
-- ── 为什么是**两列而不是一张新表** ─────────────────────────────────
--
-- 三种做法与取舍:
--
--   ① **版本列(本迁移)**:`projects.version` + `projects.parent_project_id`。
--      「v2 是 v1 的下一个」这条边**已经在 `projects` 表内部**,不新建容器。
--   ② 每次演进开一个**新表**(delivery / version 表):交付物与项目分离。
--      真机上项目**就是**交付物的容器(`works` 表用 `parent_work_id` 建树就是同一条
--      纪律的镜像),再套一层容器只是多一次身份问题。
--   ③ 单表 + 一个 `is_revision` 布尔:分不出「v2 回到 v1 再分叉」这种情况。
--
-- ⇒ 两列。`version` 是**整数自增**而不是字符串(`'v2'`):排序、比较、下一版
-- 编号全都是算术,而字符串会引出 `'v10' < 'v2'` 这类经典错误。
--
-- ── 为什么 `parent_project_id` 用 `ON DELETE SET NULL` 而不是 `CASCADE` ──
--
-- 删除一个项目**不该**把它的历史版本一起删掉 —— 那与 `artifacts.work_id`
-- (migration 014)同一条纪律:产出与记录必须比它们的容器活得久。
-- SET NULL 之后那一行退化成「一个没有前身的 v1」,**仍然读得出来**,
-- 而静默级联会把整条版本链抹成一片空白。
--
-- ⚠️ **注意**:它是自引用,所以**没有**「子表要备份」那个问题(没有别的表指向
-- `projects`,只有它自己指向自己),但**将来若有第二张表引用 projects**,重建时
-- 要一并处置 —— 与 016/020 文件头记的那个「第 N 张引用子表」的清单同一形状。
--
-- ── 为什么两列都**可空 / 有默认值** ────────────────────────────────
--
--   · `version` 缺省 **1** —— 存量项目一律是 v1,而「v1」不是编造出来的值,
--     它是**事实**:在版本链存在之前存在的每一个项目都是第一版。
--   · `parent_project_id` **可空且默认为 NULL** —— 「没有前身」是一个合法状态
--     (用户做的第一件事),不是「数据缺失」。⚠️ **不做回填**:库里没有任何一行
--     能证明某个项目是另一个的下一版(真机那两个项目是**分别**立项的,不是版本关系);
--     回填等于编造一条祖先关系。
--
-- ── 「下一个版本」是什么(这是平台**不该**猜的东西) ──────────────
--
-- 版本链的**边**由**业务经理**建:甲方说「上一个方案的实盘那一版还要加东西」,
-- 那是**它**判断「这是同一个交付物」,平台从库里推不出来(§2.11.3)。
-- `project_open` 因此收一个 `parentProjectId` 参数,缺省就是「一个新项目」。
--
-- ⚠️ **版本链不是继承**:`v2` **不会**自动继承 `v1` 的工作项、工件或对话 ——
-- 那是一次真实的重新立项。它继承的是**身份**(「这是 v1 的下一个」),
-- 而业务经理靠 `parentProjectId` + `project_read` 自己去把 v1 的东西读出来。
--
-- ── 本迁移只做加法 ──────────────────────────────────────────────
--
-- 两条 `ALTER TABLE ... ADD COLUMN`,**一行 DROP 都没有**,不改任何已有列、
-- 不重建表、不改任何既有约束。
-- ⇒ 023 **不是** `INTENTIONAL_REBUILDS` 的成员,`tests/platform/migrations.test.ts`
-- 的重名守卫不会把它当成「同一张表被两个迁移创建」。

-- ── ① 这是第几版 ──────────────────────────────────────────────────
--
-- 从 1 开始。**不用字符串**(见文件头):`'v2'` 会让排序与「下一版编号」变成两套
-- 各自出错的逻辑,而算术没有这个问题。
ALTER TABLE projects ADD COLUMN version INTEGER NOT NULL DEFAULT 1;

-- ── ② 上一个版本是谁 ──────────────────────────────────────────────
--
-- **可空 = 没有前身**(用户做的第一件事、或一个历史上就独立立项的项目)。
-- SET NULL:删除一个项目不该抹掉它的版本链(见文件头)。
ALTER TABLE projects ADD COLUMN parent_project_id TEXT
  REFERENCES projects(id) ON DELETE SET NULL;