-- 037 · 工作项级验收判据(works.acceptance_criteria,2026-11-22)
--
-- ── 它补的是什么 ────────────────────────────────────────────────
--
-- 031(2026-11-15)把**项目级**验收判据升级成了结构化数据(JSON 数组,逐条
-- 可查、可引用、可核验)。但「审什么」还有一层:**工作项**——质检审的是每条
-- 产出,而 works 上只有 `title` + `goal`(散文),判据藏在 goal 自由文本里,
-- 逐条核验无从做起。multica 把 `acceptance_criteria` 放在 issue 级,正是同一
-- 个道理:验收判据要挂在「被验收的那个单元」上。
--
-- 本迁移把 031 的形状**原样**搬到工作项级:
--   · `acceptance_criteria` = JSON 数组(每条一个可检验的判据句子);
--   · `work_create` 可带、`work_update` 整体替换(与 dependsOn 同一条语义);
--   · 下游按条消费:质检逐条对照(`renderTask` 的 review_work)、
--     甲方「确认开工」卡逐条展示。
--
-- ── 为什么是纯加列,不是重建表 ────────────────────────────────────
--
-- 与 030 / 031 / 032 同一条先例:纯加列、NOT NULL 带默认、无 CHECK ——
-- 取值域(JSON 数组)在读写两侧的 TS 里校验(`repo/works.ts`,解析容错
-- 照抄 `repo/projects.ts`:坏 JSON / 类型不对 ⇒ 空数组,一个判据存坏了
-- 不该让工作项读不出来)。`works` 被三张子表引用,重建成本与收益不成比例。
--
-- ── 存量行 = 空数组 ──────────────────────────────────────────────
--
-- 与 031 对项目完全同一条纪律:存量工作项的判据躺在 goal 文本里,**不自动
-- 抽取**(机械提取自由文本是平台做不到的事)。空数组 =「还没有结构化判据」,
-- 读面如实显示「未给验收判据」,质检退回 goal 口径 —— 不伪造。

ALTER TABLE works ADD COLUMN acceptance_criteria TEXT NOT NULL DEFAULT '[]';
