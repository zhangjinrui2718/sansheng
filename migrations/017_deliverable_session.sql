-- 017 · 交付会话:会话 ↔ 交付物的那条边 + 会话的通道
--
-- ── 它补的是什么 ────────────────────────────────────────────────
--
-- 用户的原话:「业务经理拿到交付物(也是工件的一种),然后**主动发起和用户的
-- 对话,可以新建一条对话**」。而在这条迁移之前,`project_sessions` 只认识
-- 「一个项目一条连续对话」,答不出两个问题:
--
--   ① **这条对话是哪场交付开出来的?** —— 没有列可表达。
--      于是 `handover` 规则(C3,`runtime/dispatcher.ts` 的 `handover_deliverable`)
--      **没有终止判据**:「这条交付物已经交付过了」在库里没有答案,`if` 每个
--      tick 都成立,只能靠尝试预算(限流,不是判据)兜住 —— 而预算兜住的形态是
--      「系统在同一个地方跑了很多次」,那是**静默**的一种(设计 1 §2.11.4 末)。
--
--   ② **这条消息属于哪条对话?** —— 没有列可表达,于是 `ensureSession` 只能挑
--      「最新那条会话」。交付会话一建出来,后续**所有角色**的六处调用点都会把
--      消息写进它:消息一条不少,只是**分错了会话**。这是设计 1 §2.11.6 点名的
--      那条地雷,C4 必须先拆它再开第一条甲方通道会话。
--
-- ── 为什么这次可以用 ALTER ─────────────────────────────────────
--
-- 013 / 014 是纯加法,015 / 016 只能重建表 —— 因为 SQLite 改不了已有 CHECK 的
-- 表达式(`ADD CONSTRAINT` 只能**收紧**,拿去放宽会无错应用而约束一字节没变)。
-- **本迁移加的是两个全新的列**,不碰任何已有约束:
--
--   - `project_sessions` 的两个既有约束(index)都不受新列影响;
--   - `channel` 的 CHECK 是**新列自己的** CHECK,不是放宽旧闭集;
--   - `deliverable_artifact_id` 是**新的**外键(`ADD COLUMN ... REFERENCES` 实测
--     在这条链上成功,悬空引用被外键拒掉)。
--
-- ⇒ 所以 017 **不是** `INTENTIONAL_REBUILDS` 的成员:它没有任何 DROP、
-- 没有表重建、没有 ALTER 已有列。`tests/platform/migrations.test.ts` 的重名守卫
-- 因此**不会**把它当成「同一张表被两个迁移创建」。
--
-- ⚠️ **但它仍然改了 `artifacts` 的「有几张子表引用我」这个数**:从 3 条变 4 条。
-- 那个数正是 016 重建 recipe 的前提(先备份哪些子表 / 谁会跟着 DROP 静默级联)。
-- 016 的重建前提守卫跑的是 `upTo015`(版本 < 16 的迁移),所以它**看不见**这一条;
-- 于是这里显式记一笔:**将来若有第二次重建 `artifacts`,第 4 张子表是
-- `project_sessions`,动作是 `NO ACTION`(没有 ON DELETE 子句),
-- 处置方式与 `asks.resolution_artifact_id` 同形 —— 重建前先把它置 NULL、重建后回填。**
--
-- ── 本迁移只做加法 ──────────────────────────────────────────────
--
-- 两行 `ALTER TABLE ... ADD COLUMN`,**一行 DROP 都没有**(批次 18 的事故是
-- `DROP TABLE` + `ON DELETE CASCADE` 静默删光全部会话消息,012 的注释记着这条路)。
-- 存量行的处置也如实写在下面:它们全部落在 `internal`,因为**它们确实都是
-- 项目内部会话** —— 交付之前不存在第二条对话。

-- ── ① 交付会话 ↔ 交付物 ─────────────────────────────────────────
--
-- 语义:**1:1**(一条 `deliverable` 工件至多一条交付会话),**可空**。
-- NULL = 这条会话不是交付开出来的(项目主会话 / 接待会话)。
--
-- **它同时是 `handover` 规则的终止判据**(`runtime/dispatcher.ts` 的
-- `deliveredArtifactIds` 就读这一列)。列名是握手协议的一半:读面先问
-- `PRAGMA table_info`,列在才查 —— 换成别的名字,那条规则永远不会终止,
-- 而表现只是「业务经理被反复叫醒」。
--
-- ⚠️ **不带 ON DELETE 子句(= NO ACTION),这是刻意的**:删掉一条交付物
-- **不该静默删掉那场交付对话**。CASCADE 是 012 那条静默删数据的路;而工件是
-- 审计面(设计 2 §10.2:工件必须比产生它的东西活得久),所以这条边的失效方向
-- 选「响亮拒绝」而不是「静默连坐」。
ALTER TABLE project_sessions ADD COLUMN deliverable_artifact_id TEXT REFERENCES artifacts(id);

-- ── ② 会话的通道 ────────────────────────────────────────────────
--
-- `internal` = 项目的内部会话(角色回合 / 系统通知 / 工作项执行都写这里)
-- `client`   = **交付对话** —— 平台在 `handover` 回合**成功结束后**开的那条
--              (`runtime/dispatcher.ts` 的消费块第三支)
--
-- ⚠️ **`DEFAULT 'internal'` 让存量行全部落在 internal** —— 这是对的:它们都是
-- 项目内部会话(交付之前不存在第二条对话)。**但默认值只是为了让既有行有值,
-- 不许当成判据**:`ensureSession` 的通道是**调用点显式指定的实参**,不是
-- 「没传就查最新那条」(那正是 C4 要拆的地雷,设计 1 §2.11.6)。
ALTER TABLE project_sessions ADD COLUMN channel TEXT NOT NULL DEFAULT 'internal'
  CHECK (channel IN ('internal','client'));
